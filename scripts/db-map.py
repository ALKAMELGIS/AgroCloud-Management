#!/usr/bin/env python3
"""Write docs/DATABASE.md from a database that has every migration applied.

Usage: DATABASE_URL=postgresql://... python3 scripts/db-map.py
Run it after adding a migration so the map stays true.
"""
import os, subprocess, collections, re, datetime

URL = os.environ.get('DATABASE_URL')
if not URL:
    raise SystemExit('Set DATABASE_URL to a database with all migrations applied')

def q(sql):
    out = subprocess.run(['psql', URL, '-tA', '-F', '\t', '-c', sql], capture_output=True, text=True, check=True).stdout
    return [l.split('\t') for l in out.splitlines() if l]

tables = [r[0] for r in q("select table_name from information_schema.tables where table_schema='public' and table_type='BASE TABLE' and table_name not in ('spatial_ref_sys','_migrations') order by 1")]
cols = collections.defaultdict(list)
for t, c, ty, nn in q("select table_name, column_name, data_type, is_nullable from information_schema.columns where table_schema='public' order by table_name, ordinal_position"):
    cols[t].append((c, ty, nn))
fks = collections.defaultdict(list)
for t, c, rt in q("""select tc.table_name, kcu.column_name, ccu.table_name from information_schema.table_constraints tc
  join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
  join information_schema.constraint_column_usage ccu on ccu.constraint_name = tc.constraint_name and ccu.table_schema = tc.table_schema
  where tc.constraint_type = 'FOREIGN KEY' and tc.table_schema = 'public' order by 1, 2"""):
    fks[t].append((c, rt))

GROUPS = [
    ('Tenancy, people and access', r'^(organizations|organization_invites|plan_editions|users|user_|refresh_tokens|password_reset|email_verifications|feature_flags|system_settings|api_keys|push_tokens|team_assignments|workers|org_catalog_hidden)'),
    ('Farm structure and seasons', r'^(countries|sites|farm_area|fields|field_types|valves|seasons|season_|crops|crop_|field_soil|field_sampling|planting_records|open_field_planting|plantation_|germination|nursery|breeders)'),
    ('Daily records', r'^(harvest|ecph_|fertigation_|fertilizer_|irrigation_|recipe|pump_room|site_pump|weather_|soil_sensor|agronomic_thresholds|inventory_|equipment|cost_)'),
    ('Crop protection (IPM)', r'^(pesticide_|site_pesticide|site_product|phi_|spray_|scouting_|pest_|bio_|site_bio|bumble_bee|ipm_)'),
    ('Team and tasks', r'^(manpower_|tasks|task_|shift)'),
    ('GIS, remote sensing and devices', r'^(gis_|geo_|gps_|drone_|john_deere|form_registry|form_feeds|feed_keys)'),
    ('AI assistant', r'^(ai_)'),
    ('Forms, reports and notifications', r'^(form_templates|site_form_templates|scheduled_reports|notification|user_notifications|alert_|attachments|entity_comments|file_blobs|app_summary|audit_logs|webhook|api_integration|api_sync)'),
    ('Training (internship)', r'^(training_|lesson_|student_)'),
]
grouped = collections.OrderedDict((g, []) for g, _ in GROUPS)
grouped['Other'] = []
for t in tables:
    for g, rx in GROUPS:
        if re.search(rx, t):
            grouped[g].append(t); break
    else:
        grouped['Other'].append(t)

out = []
out.append('# AgroCloud database map\n')
out.append(f'Generated by `scripts/db-map.py` on {datetime.date.today().isoformat()} from a database with every migration applied ({len(tables)} tables). PostgreSQL 16 with PostGIS; geometry is WGS 84 (SRID 4326).\n')
out.append('## How the data hangs together\n')
out.append('```mermaid\nerDiagram\n  organizations ||--o{ countries : owns\n  countries ||--o{ sites : has\n  sites ||--o{ farm_areas : has\n  farm_areas ||--o{ fields : has\n  fields ||--o{ harvests : records\n  fields ||--o{ ecph_entries : records\n  ecph_entries ||--o{ ecph_valve_readings : "per valve"\n  fields ||--o{ fertigation_entries : records\n  fields ||--o{ pesticide_applications : records\n  pesticide_products ||--o{ pesticide_applications : "product used"\n  fields ||--o{ crop_history : "crop over time"\n  crops ||--o{ crop_varieties : has\n  organizations ||--o{ users : employs\n  plan_editions ||--o{ organizations : "edition of"\n```\n')
out.append('Rules every table follows:\n')
out.append('- Every business row belongs to one organization (`organization_id`, directly or through its field). Queries filter by it.')
out.append('- A field is found by `Farm_Code + ZONE_ID` from GIS, or by its name; imports match names without spaces, dashes or leading zeros.')
out.append('- Soft delete where history matters: users, sites and fields keep `deleted_at`; an organization is switched off with `is_active`. Records are corrected through change requests, not deleted.')
out.append('- Plan limits on sites, fields and users are checked in the database (`agro_plan_limit()` trigger, migration 181).\n')
out.append('## Tables by area\n')
for g, ts in grouped.items():
    if not ts: continue
    out.append(f'### {g} ({len(ts)})\n')
    out.append('| Table | Columns | Links to |')
    out.append('|---|---|---|')
    for t in ts:
        cs = cols[t]
        names = ', '.join(c for c, _, _ in cs if c not in ('id', 'created_at', 'updated_at'))
        if len(names) > 220: names = names[:217] + '…'
        links = ', '.join(sorted({f'{rt} ({c})' for c, rt in fks[t]}))
        out.append(f'| `{t}` | {names} | {links or "—"} |')
    out.append('')
open(os.path.join(os.path.dirname(__file__), '..', 'docs', 'DATABASE.md'), 'w').write('\n'.join(out) + '\n')
print('docs/DATABASE.md:', len(tables), 'tables,', {g: len(t) for g, t in grouped.items()})
